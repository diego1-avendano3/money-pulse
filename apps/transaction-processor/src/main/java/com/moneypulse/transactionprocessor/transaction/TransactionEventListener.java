package com.moneypulse.transactionprocessor.transaction;

import java.time.Clock;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.data.r2dbc.core.R2dbcEntityOperations;
import org.springframework.kafka.annotation.KafkaListener;
import org.springframework.stereotype.Component;
import tools.jackson.databind.json.JsonMapper;

/**
 * Subscribes to {@link Topics#TRANSACTIONS_RECEIVED}. The topic value is plain
 * JSON text, not a {@code JsonSerializer<T>} payload (spec §4.7), so the listener
 * deserializes it by hand with the Boot-managed {@link JsonMapper} before mapping
 * to a {@link TransactionRow} and persisting it with {@code .block()} (spec §4.6
 * Option A -- blocking the listener thread on R2DBC is the deliberate choice for
 * Phase 0).
 *
 * <p>Uses {@link R2dbcEntityOperations#insert(Object) insert}, not a
 * {@code ReactiveCrudRepository.save(...)}: {@code TransactionRow}'s id is
 * assigned by the event, not generated by the database, and Spring Data R2DBC's
 * {@code save()} treats a non-null id as "already exists" and issues an UPDATE
 * -- which silently affects zero rows instead of inserting. {@code insert()}
 * always inserts, which also matches Phase 0's semantics: the processor never
 * updates a row (dedup/upsert is Phase 2).
 */
@Component
class TransactionEventListener {

    private static final Logger log = LoggerFactory.getLogger(TransactionEventListener.class);

    private final R2dbcEntityOperations entityOperations;
    private final JsonMapper jsonMapper;
    private final Clock clock;

    TransactionEventListener(R2dbcEntityOperations entityOperations, JsonMapper jsonMapper, Clock clock) {
        this.entityOperations = entityOperations;
        this.jsonMapper = jsonMapper;
        this.clock = clock;
    }

    @KafkaListener(topics = Topics.TRANSACTIONS_RECEIVED)
    void onMessage(String payload) {
        TransactionEvent event = jsonMapper.readValue(payload, TransactionEvent.class);
        entityOperations.insert(toRow(event)).block();
        // Without a log line here, nothing observes the traceId this listener
        // invocation carries (observation-enabled propagates it into the MDC,
        // but an empty method body never surfaces it) -- spec V6 greps both
        // services' logs for the same traceId.
        log.info("Persisted transaction {}", event.id());
    }

    private TransactionRow toRow(TransactionEvent event) {
        return new TransactionRow(
                event.id(),
                event.accountId(),
                event.amount(),
                event.currency(),
                event.merchant(),
                event.occurredAt(),
                event.receivedAt(),
                clock.instant());
    }
}
